"""Generate the Claude Code and Antigravity agent files of a plugin from one set of role sources.

    uv run tools/build.py            # write the generated files and update the manifest
    uv run tools/build.py --check    # fail if anything generated is out of date or a rule is broken

Sources: ``<plugin>/src/roles/<role>.md`` (YAML frontmatter + prompt). A role declares abstract
capabilities; this script maps them to each CLI's real tool names and refuses names it does not know.
"""

import argparse
import json
import sys
from dataclasses import dataclass, field
from enum import StrEnum
from pathlib import Path

import yaml

ENCODING = "utf-8"
ROLES_DIR = Path("src") / "roles"
CLAUDE_AGENTS_DIR = Path("claude") / "agents"
ANTIGRAVITY_AGENTS_DIR = Path("agents")
CLAUDE_MANIFEST = Path(".claude-plugin") / "plugin.json"
MARKDOWN_SUFFIX = ".md"
FRONTMATTER_FENCE = "---"
DEFAULT_PLUGIN = Path("families") / "software-dev" / "core"
MODEL_SETTING = "inherit"
AGENT_NAME_SEPARATOR = "-"
GENERATED_NOTE = "<!-- Generated by tools/build.py from {source}. Do not edit: edit the source and rebuild. -->"
JSON_INDENT = 2


class Capability(StrEnum):
    READ = "read"
    EDIT = "edit"
    RUN = "run"
    # The agentflow MCP tools: the ones every role uses, and the one that writes project documents.
    WORKSPACE = "workspace"
    PROJECT = "project"


class ManifestKey(StrEnum):
    AGENTS = "agents"


class Tier(StrEnum):
    """Plan-item tiers (``tier:`` in a plan). A role with variants has one agent per tier: ``<role>-<tier>``."""

    FAST = "fast"
    DEEP = "deep"


class Cli(StrEnum):
    CLAUDE = "claude"
    ANTIGRAVITY = "antigravity"


class RoleKey(StrEnum):
    """Frontmatter keys of a role source."""

    NAME = "name"
    DESCRIPTION = "description"
    CAPABILITIES = "capabilities"
    # One agent with these settings, or one agent per tier. Neither: the agent inherits the session's model.
    SETTINGS = "settings"
    VARIANTS = "variants"


class SettingKey(StrEnum):
    MODEL = "model"
    EFFORT = "effort"


# Model and effort values from each CLI's documentation (Claude Code: sub-agents and model-config; Antigravity:
# subagents). Aliases, not pinned versions: the CLI resolves them to its current recommended model. Antigravity has
# no effort setting.
CLAUDE_MODELS = frozenset({"sonnet", "opus", "haiku", "fable", MODEL_SETTING})
CLAUDE_EFFORTS = frozenset({"low", "medium", "high", "xhigh", "max"})
ANTIGRAVITY_MODELS = frozenset({MODEL_SETTING, "flash", "pro"})
ALLOWED_SETTINGS = {
    Cli.CLAUDE: {SettingKey.MODEL: CLAUDE_MODELS, SettingKey.EFFORT: CLAUDE_EFFORTS},
    Cli.ANTIGRAVITY: {SettingKey.MODEL: ANTIGRAVITY_MODELS},
}
TIER_DESCRIPTION = " Takes the plan items whose tier is {tier}{extra}."
DEEP_EXTRA = " (and those with no tier)"


# Tool names, from each CLI's documentation. Antigravity's names are the ones its hooks reference
# documents for the CLI (its SDK uses other names and must not be mixed in).
# The MCP server belongs to dev-core, so every plugin's agents name its tools with dev-core's prefix:
# mcp__plugin_<plugin>_<server>__<tool> (checked in a real session, see docs/mcp-notes.md).
MCP_SERVER_PREFIX = "mcp__plugin_dev-core_agentflow__"
WORKSPACE_TOOL_NAMES = (
    "status", "next_step", "plan_check", "report_write", "scan_summary", "conventions", "knowledge_search", "knowledge_read",
)  # fmt: skip
PROJECT_TOOL_NAMES = ("project_write", "replan_write")
WORKSPACE_TOOLS = tuple(MCP_SERVER_PREFIX + name for name in WORKSPACE_TOOL_NAMES)
PROJECT_TOOLS = tuple(MCP_SERVER_PREFIX + name for name in PROJECT_TOOL_NAMES)
CLAUDE_TOOLS = {
    Capability.READ: ("Read", "Glob", "Grep"),
    Capability.EDIT: ("Edit", "Write"),
    Capability.RUN: ("Bash", "PowerShell"),
    Capability.WORKSPACE: WORKSPACE_TOOLS,
    Capability.PROJECT: PROJECT_TOOLS,
}
# Antigravity's `tools:` takes built-in tools only, and MCP tools reach every agent whatever it lists, so these
# capabilities add nothing there.
ANTIGRAVITY_TOOLS = {
    Capability.READ: ("view_file", "list_dir", "find_by_name", "grep_search"),
    Capability.EDIT: ("write_to_file", "replace_file_content", "multi_replace_file_content"),
    Capability.RUN: ("run_command",),
    Capability.WORKSPACE: (),
    Capability.PROJECT: (),
}
# Everything a tool list is allowed to contain. Edit tools are the ones a read-only role must never get;
# Bash, PowerShell and run_command can change files too, which is why those roles also write through agentflow.
CLAUDE_ALLOWED = frozenset(
    {"Agent", "Bash", "Edit", "Glob", "Grep", "LSP", "NotebookEdit", "PowerShell", "Read", "Skill", "TodoWrite", "WebFetch", "WebSearch", "Write"}
    | set(WORKSPACE_TOOLS)
    | set(PROJECT_TOOLS)
)
CLAUDE_EDIT_TOOLS = frozenset({"Edit", "Write", "NotebookEdit"})
ANTIGRAVITY_ALLOWED = frozenset(
    {
        "view_file",
        "write_to_file",
        "replace_file_content",
        "multi_replace_file_content",
        "list_dir",
        "find_by_name",
        "grep_search",
        "run_command",
    }
)
ANTIGRAVITY_EDIT_TOOLS = frozenset({"write_to_file", "replace_file_content", "multi_replace_file_content"})
# Roles that must never get an edit tool. Tester may (it writes tests); implementer is the code writer.
READ_ONLY_ROLES = frozenset({"orchestrator", "planner", "security", "reviewer", "scout"})
# The only role that writes project documents (with the `project` capability).
PROJECT_WRITERS = frozenset({"scout"})


class BuildError(Exception):
    pass


Settings = dict[Cli, dict[SettingKey, str]]


@dataclass(frozen=True)
class Role:
    name: str
    description: str
    capabilities: tuple[Capability, ...]
    prompt: str
    source: Path
    # Agent name -> model settings per CLI. A role without ``settings``/``variants`` is one agent that inherits.
    agents: dict[str, Settings] = field(default_factory=dict)
    # Tier of each agent name, for roles with variants (it goes into the description).
    tiers: dict[str, Tier] = field(default_factory=dict)


def split_frontmatter(text: str, source: Path) -> tuple[dict, str]:
    lines = text.replace("\r\n", "\n").split("\n")
    if lines[0] != FRONTMATTER_FENCE or FRONTMATTER_FENCE not in lines[1:]:
        raise BuildError(f"{source}: missing '---' frontmatter")
    end = lines.index(FRONTMATTER_FENCE, 1)
    data = yaml.safe_load("\n".join(lines[1:end]))
    if not isinstance(data, dict):
        raise BuildError(f"{source}: frontmatter is not a mapping")
    return data, "\n".join(lines[end + 1 :]).strip("\n")


def load_role(path: Path) -> Role:
    data, prompt = split_frontmatter(path.read_text(encoding=ENCODING), path)
    unknown = set(data) - {key.value for key in RoleKey}
    if unknown:
        raise BuildError(f"{path}: unknown frontmatter keys: {', '.join(sorted(unknown))}")
    name, description, raw = data.get("name"), data.get("description"), data.get("capabilities")
    if name != path.stem:
        raise BuildError(f"{path}: name '{name}' must equal the file name '{path.stem}'")
    if not isinstance(description, str) or not description.strip():
        raise BuildError(f"{path}: description is required")
    if not isinstance(raw, list) or not raw:
        raise BuildError(f"{path}: capabilities must be a non-empty list")
    try:
        capabilities = tuple(Capability(item) for item in raw)
    except ValueError as exc:
        raise BuildError(f"{path}: {exc}; allowed: {', '.join(Capability)}") from exc
    if not prompt.strip():
        raise BuildError(f"{path}: the prompt is empty")
    if name in READ_ONLY_ROLES and Capability.EDIT in capabilities:
        raise BuildError(f"{path}: role '{name}' is read-only and must not have the 'edit' capability")
    if Capability.PROJECT in capabilities and name not in PROJECT_WRITERS:
        raise BuildError(f"{path}: only {', '.join(sorted(PROJECT_WRITERS))} may have the 'project' capability")
    agents, tiers = load_agents(name, data, path)
    return Role(name, description.strip(), capabilities, prompt, path, agents, tiers)


def parse_settings(raw: object, where: Path, label: str) -> Settings:
    """Model settings per CLI, checked against the values each CLI's documentation lists."""
    if not isinstance(raw, dict) or not raw:
        raise BuildError(f"{where}: {label} must map each CLI ({', '.join(Cli)}) to its model settings")
    settings: Settings = {}
    for cli_name, values in raw.items():
        try:
            cli = Cli(cli_name)
        except ValueError as exc:
            raise BuildError(f"{where}: {label}: unknown CLI '{cli_name}' (allowed: {', '.join(Cli)})") from exc
        if not isinstance(values, dict) or SettingKey.MODEL not in values:
            raise BuildError(f"{where}: {label}.{cli} needs at least '{SettingKey.MODEL}'")
        checked: dict[SettingKey, str] = {}
        for key, value in values.items():
            try:
                setting = SettingKey(key)
            except ValueError as exc:
                raise BuildError(f"{where}: {label}.{cli}: unknown setting '{key}' (allowed: {', '.join(ALLOWED_SETTINGS[cli])})") from exc
            allowed = ALLOWED_SETTINGS[cli].get(setting)
            if allowed is None:
                raise BuildError(f"{where}: {label}.{cli}: {cli} has no '{setting}' setting")
            if value not in allowed:
                raise BuildError(f"{where}: {label}.{cli}.{setting}: '{value}' is not one of {', '.join(sorted(allowed))}")
            checked[setting] = value
        settings[cli] = checked
    missing = [cli for cli in Cli if cli not in settings]
    if missing:
        raise BuildError(f"{where}: {label} lacks settings for {', '.join(missing)}")
    return settings


def load_agents(name: str, data: dict, path: Path) -> tuple[dict[str, Settings], dict[str, Tier]]:
    """The agents of a role: one, or one per tier (``<role>-<tier>``)."""
    single, variants = data.get(RoleKey.SETTINGS), data.get(RoleKey.VARIANTS)
    if single is not None and variants is not None:
        raise BuildError(f"{path}: give '{RoleKey.SETTINGS}' or '{RoleKey.VARIANTS}', not both")
    if variants is None:
        settings = parse_settings(single, path, RoleKey.SETTINGS) if single is not None else inherited()
        return {name: settings}, {}
    if not isinstance(variants, dict) or set(variants) != {tier.value for tier in Tier}:
        raise BuildError(f"{path}: '{RoleKey.VARIANTS}' needs exactly the tiers {', '.join(Tier)}")
    agents, tiers = {}, {}
    for tier in Tier:
        agent = f"{name}{AGENT_NAME_SEPARATOR}{tier}"
        agents[agent] = parse_settings(variants[tier], path, f"{RoleKey.VARIANTS}.{tier}")
        tiers[agent] = tier
    return agents, tiers


def inherited() -> Settings:
    return {cli: {SettingKey.MODEL: MODEL_SETTING} for cli in Cli}


def load_roles(plugin: Path) -> list[Role]:
    sources = sorted((plugin / ROLES_DIR).glob(f"*{MARKDOWN_SUFFIX}"))
    if not sources:
        raise BuildError(f"no role sources in {plugin / ROLES_DIR}")
    return [load_role(path) for path in sources]


def tools_for(role: Role, mapping: dict[Capability, tuple[str, ...]]) -> list[str]:
    ordered = [cap for cap in Capability if cap in role.capabilities]
    return [tool for cap in ordered for tool in mapping[cap]]


def check_tools(role: Role, tools: list[str], allowed: frozenset[str], edit_tools: frozenset[str], cli: str) -> None:
    unknown = [tool for tool in tools if tool not in allowed]
    if unknown:
        raise BuildError(f"{role.source}: {cli} tools not in the documented list: {', '.join(unknown)}")
    if role.name in READ_ONLY_ROLES and edit_tools.intersection(tools):
        raise BuildError(f"{role.source}: read-only role '{role.name}' got {cli} edit tools")


def render(frontmatter: dict, role: Role) -> str:
    head = yaml.safe_dump(frontmatter, sort_keys=False, allow_unicode=True, width=10_000).strip()
    note = GENERATED_NOTE.format(source=f"src/roles/{role.source.name}")
    return f"{FRONTMATTER_FENCE}\n{head}\n{FRONTMATTER_FENCE}\n{note}\n\n{role.prompt}\n"


def agent_description(role: Role, agent: str) -> str:
    tier = role.tiers.get(agent)
    if tier is None:
        return role.description
    return role.description + TIER_DESCRIPTION.format(tier=tier, extra=DEEP_EXTRA if tier is Tier.DEEP else "")


def claude_agent(role: Role, agent: str) -> str:
    tools = tools_for(role, CLAUDE_TOOLS)
    check_tools(role, tools, CLAUDE_ALLOWED, CLAUDE_EDIT_TOOLS, "Claude Code")
    frontmatter = {
        "name": agent,
        "description": agent_description(role, agent),
        "tools": ", ".join(tools),
        **{str(key): value for key, value in role.agents[agent][Cli.CLAUDE].items()},
    }
    return render(frontmatter, role)


def antigravity_agent(role: Role, agent: str) -> str:
    tools = tools_for(role, ANTIGRAVITY_TOOLS)
    check_tools(role, tools, ANTIGRAVITY_ALLOWED, ANTIGRAVITY_EDIT_TOOLS, "Antigravity")
    frontmatter = {
        "name": agent,
        "description": agent_description(role, agent),
        "tools": tools,
        **{str(key): value for key, value in role.agents[agent][Cli.ANTIGRAVITY].items()},
    }
    return render(frontmatter, role)


def manifest_text(plugin: Path, roles: list[Role]) -> str:
    path = plugin / CLAUDE_MANIFEST
    manifest = json.loads(path.read_text(encoding=ENCODING))
    names = sorted(agent for role in roles for agent in role.agents)
    manifest[ManifestKey.AGENTS] = [f"./{(CLAUDE_AGENTS_DIR / (agent + MARKDOWN_SUFFIX)).as_posix()}" for agent in names]
    return json.dumps(manifest, indent=JSON_INDENT, ensure_ascii=False) + "\n"


CHECKLISTS_BEGIN = "<!-- BEGIN:checklists -->"
CHECKLISTS_END = "<!-- END:checklists -->"
USAGE_FILE = "USAGE.md"
WORKFLOW_FILE = "workflow.yaml"
# What each source of dynamic lines adds to a checklist (agentflow writes them from the step's report).
ITEM_SOURCES = {
    "plan-items": "một ô `C<n>` cho mỗi mục của kế hoạch (`plan-items`)",
    "review-conventions": "một ô `PC-xx` cho mỗi quy ước `check: review` đang hiệu lực (`review-conventions`)",
    "spec-items": "một ô `C<n>` cho mỗi mục kế hoạch, kèm test, lệnh và kết quả agentflow tự chạy lại (`spec-items`)",
    "drift-proposals": "một ô `D<n>` cho mỗi đề xuất ở mục `## Đề xuất cập nhật hồ sơ` (`drift-proposals`)",
}


def checklists_block(plugin: Path) -> str:
    """The text between the markers of USAGE.md: the fixed questions of every approval, from the plugin's workflow."""
    data = yaml.safe_load((plugin / WORKFLOW_FILE).read_text(encoding="utf-8"))
    parts = []
    for step in data["steps"]:
        questions, sources = step.get("approval_checklist", []), step.get("approval_items", [])
        if not (questions or sources):
            continue
        label = step["id"].capitalize()
        # `Review — Review` would say it twice; the older documents wrote `Review — mỗi quy ước có dòng đánh giá`.
        title = "những gì bạn kiểm" if step["name"].lower() == step["id"] else step["name"]
        lines = [f"**{label} — {title}** (`{step['id']}`)"]
        lines += [f"- [ ] {question}" for question in questions]
        lines += [f"- Thêm tự động: {ITEM_SOURCES[source]}." for source in sources]
        parts.append("\n".join(lines))
    return "\n\n" + "\n\n".join(parts) + "\n\n"


def usage_text(plugin: Path) -> tuple[Path, str] | None:
    """USAGE.md next to the plugin with its generated block brought up to date; ``None`` when there is nothing to generate."""
    usage = plugin.parent / USAGE_FILE
    if not (plugin / WORKFLOW_FILE).is_file() or not usage.is_file():
        return None
    text = usage.read_text(encoding="utf-8")
    if text.count(CHECKLISTS_BEGIN) != 1 or text.count(CHECKLISTS_END) != 1 or text.index(CHECKLISTS_BEGIN) > text.index(CHECKLISTS_END):
        raise BuildError(f"{usage}: needs exactly one {CHECKLISTS_BEGIN} ... {CHECKLISTS_END} block (the checklists are generated there)")
    head, rest = text.split(CHECKLISTS_BEGIN, 1)
    tail = rest.split(CHECKLISTS_END, 1)[1]
    return usage, f"{head}{CHECKLISTS_BEGIN}{checklists_block(plugin)}{CHECKLISTS_END}{tail}"


def expected_files(plugin: Path) -> dict[Path, str]:
    """Every generated file (path -> content), validating the sources on the way."""
    roles = load_roles(plugin)
    files: dict[Path, str] = {}
    for role in roles:
        for agent in role.agents:
            files[plugin / CLAUDE_AGENTS_DIR / f"{agent}{MARKDOWN_SUFFIX}"] = claude_agent(role, agent)
            files[plugin / ANTIGRAVITY_AGENTS_DIR / f"{agent}{MARKDOWN_SUFFIX}"] = antigravity_agent(role, agent)
    files[plugin / CLAUDE_MANIFEST] = manifest_text(plugin, roles)
    generated_usage = usage_text(plugin)
    if generated_usage is not None:
        files[generated_usage[0]] = generated_usage[1]
    return files


def stale_files(plugin: Path, expected: dict[Path, str]) -> list[Path]:
    """Agent files on disk that no role produces any more."""
    found = [
        path
        for directory in (plugin / CLAUDE_AGENTS_DIR, plugin / ANTIGRAVITY_AGENTS_DIR)
        if directory.is_dir()
        for path in directory.glob(f"*{MARKDOWN_SUFFIX}")
    ]
    return sorted(path for path in found if path not in expected)


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode(ENCODING))  # LF endings on every platform


def read_text(path: Path) -> str | None:
    # A checkout with autocrlf turns LF into CRLF; that is not drift.
    return path.read_bytes().decode(ENCODING).replace("\r\n", "\n") if path.is_file() else None


def build(plugin: Path) -> list[Path]:
    """Write all generated files; return those that changed. Removes stale agent files."""
    expected = expected_files(plugin)
    changed = []
    for path, text in expected.items():
        if read_text(path) != text:
            write_text(path, text)
            changed.append(path)
    for path in stale_files(plugin, expected):
        path.unlink()
        changed.append(path)
    return changed


def check(plugin: Path) -> list[str]:
    """Problems found; empty when everything generated is up to date."""
    try:
        expected = expected_files(plugin)
    except BuildError as exc:
        if USAGE_FILE in str(exc):
            return [f"out of date: {exc}"]
        raise
    problems = [f"out of date: {path}" for path, text in expected.items() if read_text(path) != text]
    problems += [f"stale: {path}" for path in stale_files(plugin, expected)]
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--plugin", type=Path, default=DEFAULT_PLUGIN, help="plugin directory (default: dev-core)")
    parser.add_argument("--check", action="store_true", help="only verify; exit 1 if anything is out of date")
    args = parser.parse_args(argv)
    try:
        if args.check:
            problems = check(args.plugin)
            for problem in problems:
                print(problem, file=sys.stderr)
            if problems:
                print("run `uv run tools/build.py` to regenerate", file=sys.stderr)
            else:
                print("generated files are up to date")
            return 1 if problems else 0
        changed = build(args.plugin)
    except BuildError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    print("\n".join(f"wrote {path}" for path in changed) if changed else "nothing to do")
    return 0


if __name__ == "__main__":
    sys.exit(main())
