"""Project-level copies of Claude Code plugin agents that carry the tools a person granted.

A plugin agent's ``tools`` list is fixed by the plugin, and Claude Code ignores ``mcpServers`` for plugin agents, so the
documented way to give a role more tools in one project without editing the plugin is an agent in the project's own
``.claude/agents/``. Each copy is named ``project-<agent>``, holds the plugin agent's prompt with the granted tools added
to ``tools``, and stays out of git through ``.git/info/exclude``.
"""

import hashlib
from collections.abc import Mapping, Sequence
from pathlib import Path

import yaml

from agentflow.constants import (
    CLAUDE_PROJECT_AGENTS_DIR,
    ENCODING,
    MARKDOWN_SUFFIX,
    PROJECT_AGENT_MARKER,
    PROJECT_AGENT_PREFIX,
    ExitCode,
)
from agentflow.errors import AgentflowError
from agentflow.fsutil import write_text_atomic

FENCE = "---"
TOOL_SEPARATOR = ", "
CURRENT, STALE, MISSING = "current", "stale", "missing"
NOTE = "Project copy of the plugin agent `{name}` with the tools a person granted ({tools}). Use it for this project's items."
_OLD_NOTE_PREFIX = "<!-- Generated by tools/build.py"


def project_agent_name(agent: str) -> str:
    return f"{PROJECT_AGENT_PREFIX}{agent}"


def project_agent_file(agent: str) -> str:
    return f"{project_agent_name(agent)}{MARKDOWN_SUFFIX}"


def split_agent_file(text: str) -> tuple[dict, str]:
    lines = text.replace("\r\n", "\n").split("\n")
    if not lines or lines[0] != FENCE or FENCE not in lines[1:]:
        raise ValueError("no frontmatter")
    end = lines.index(FENCE, 1)
    data = yaml.safe_load("\n".join(lines[1:end]))
    if not isinstance(data, dict):
        raise ValueError("frontmatter is not a mapping")
    return data, "\n".join(lines[end + 1 :]).strip("\n")


class ClaudeAgentOverlay:
    """``AgentOverlay`` for Claude Code: ``<project>/.claude/agents/project-<agent>.md``."""

    def __init__(self, project_root: Path, source_dirs: Sequence[Path]) -> None:
        self.directory = project_root / CLAUDE_PROJECT_AGENTS_DIR
        self.source_dirs = tuple(source_dirs)

    def render(self, tools_by_agent: Mapping[str, Sequence[str]]) -> dict[str, str]:
        """File name -> content for every plugin agent that has tools to add (``tools_by_agent``: agent -> granted tools)."""
        return {project_agent_file(agent): self._render_one(agent, tools) for agent, tools in tools_by_agent.items() if tools}

    def write(self, files: Mapping[str, str]) -> list[str]:
        changes: list[str] = []
        self.directory.mkdir(parents=True, exist_ok=True)
        for name, content in files.items():
            path = self.directory / name
            if not path.is_file() or path.read_bytes().decode(ENCODING).replace("\r\n", "\n") != content:
                write_text_atomic(path, content)
                changes.append(f"wrote {CLAUDE_PROJECT_AGENTS_DIR}/{name}")
        for path in sorted(self.directory.glob(f"{PROJECT_AGENT_PREFIX}*{MARKDOWN_SUFFIX}")):
            if path.name not in files and self._is_ours(path):
                path.unlink()
                changes.append(f"removed {CLAUDE_PROJECT_AGENTS_DIR}/{path.name}")
        return changes

    def state(self, files: Mapping[str, str]) -> dict[str, str]:
        found = {}
        for name, content in files.items():
            path = self.directory / name
            if not path.is_file():
                found[name] = MISSING
            else:
                found[name] = CURRENT if path.read_bytes().decode(ENCODING).replace("\r\n", "\n") == content else STALE
        return found

    # ------------------------------------------------------------------ helpers

    def _render_one(self, agent: str, tools: Sequence[str]) -> str:
        source = self._source(agent)
        raw = source.read_bytes()
        try:
            header, body = split_agent_file(raw.decode(ENCODING))
        except ValueError as exc:
            raise AgentflowError(f"{source}: cannot read the agent file ({exc})", ExitCode.ROLE_GRANT_REFUSED) from exc
        existing = [item.strip() for item in str(header.get("tools", "")).split(",") if item.strip()]
        merged = [*existing, *(tool for tool in tools if tool not in existing)]
        header = {
            **header,
            "name": project_agent_name(agent),
            "description": f"{header.get('description', '')} {NOTE.format(name=agent, tools=', '.join(tools))}".strip(),
            "tools": TOOL_SEPARATOR.join(merged),
        }
        digest = hashlib.sha256(raw).hexdigest()
        marker = f"<!-- {PROJECT_AGENT_MARKER} from {source.name} (sha256 {digest}). Do not edit: change the grants with `agentflow role grant|revoke`. -->"
        text = "\n".join(line for line in body.split("\n") if not line.startswith(_OLD_NOTE_PREFIX)).strip("\n")
        head = yaml.safe_dump(header, sort_keys=False, allow_unicode=True, width=10_000).strip()
        return f"{FENCE}\n{head}\n{FENCE}\n{marker}\n\n{text}\n"

    def _source(self, agent: str) -> Path:
        for directory in self.source_dirs:
            candidate = directory / f"{agent}{MARKDOWN_SUFFIX}"
            if candidate.is_file():
                return candidate
        searched = ", ".join(str(directory) for directory in self.source_dirs) or "nowhere"
        raise AgentflowError(
            f"the plugin agent '{agent}' was not found (looked in: {searched}); the plugin that defines it must be installed "
            "and the workspace's workflow/extension source paths must still exist (`agentflow workflow sync`, `agentflow ext sync`)",
            ExitCode.ROLE_GRANT_REFUSED,
        )

    @staticmethod
    def _is_ours(path: Path) -> bool:
        return PROJECT_AGENT_MARKER in path.read_bytes().decode(ENCODING, errors="replace")
