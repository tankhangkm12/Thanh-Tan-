"""state.json is the source of truth; STATE.md is regenerated from it on every save."""

import json
from collections import Counter
from collections.abc import Callable
from datetime import UTC, datetime
from pathlib import Path

from agentflow.constants import (
    ENCODING,
    IN_FLIGHT_TASK_STATUSES,
    STATE_FILE,
    STATE_MD_FILE,
    STATE_SCHEMA_FILE,
    ExitCode,
    StepStatus,
    TaskStatus,
)
from agentflow.engine import next_action
from agentflow.errors import AgentflowError
from agentflow.fsutil import write_text_atomic
from agentflow.integrity import Integrity, sha256_hex
from agentflow.models import State, Task, Workflow, state_from_dict, state_to_dict
from agentflow.render import NONE_TEXT, describe_action, describe_step
from agentflow.validation import schema_errors

TIMESTAMP_FORMAT = "%Y-%m-%dT%H:%M:%SZ"
JSON_INDENT = 2
GENERATED_NOTE = f"<!-- Generated by agentflow from {STATE_FILE}. Do not edit: every save overwrites this file. -->"
_INDENT = "\n  - "

# The task shapes the engine produces (see agentflow.engine).
ALLOWED_STEP_STATUSES = {
    TaskStatus.OPEN: frozenset({StepStatus.IN_PROGRESS, StepStatus.AWAITING_APPROVAL}),
    TaskStatus.BLOCKED: frozenset({StepStatus.FAILED}),
    TaskStatus.DONE: frozenset({StepStatus.PASSED}),
    TaskStatus.CANCELLED: frozenset(StepStatus),
}


def utc_now() -> str:
    return datetime.now(UTC).strftime(TIMESTAMP_FORMAT)


class JsonStateStore:
    """``StateStore`` over ``<workspace>/state.json`` and ``<workspace>/STATE.md``."""

    def __init__(self, workspace_dir: Path, workflow: Workflow, clock: Callable[[], str] = utc_now) -> None:
        self.state_path = workspace_dir / STATE_FILE
        self.state_md_path = workspace_dir / STATE_MD_FILE
        self.workflow = workflow
        self._clock = clock

    def load(self) -> State:
        if not self.state_path.is_file():
            raise AgentflowError(f"state file not found: {self.state_path}", ExitCode.NO_WORKSPACE)
        try:
            data = json.loads(self.state_path.read_text(encoding=ENCODING))
        except (json.JSONDecodeError, UnicodeDecodeError) as exc:
            raise AgentflowError(f"{self.state_path}: not valid JSON: {exc}", ExitCode.INVALID_STATE) from exc
        problems = schema_errors(data, STATE_SCHEMA_FILE)
        if not problems:
            state = state_from_dict(data)
            problems = state_problems(state, self.workflow)
        if problems:
            raise AgentflowError(
                f"{self.state_path}: invalid state:{_INDENT}{_INDENT.join(problems)}", ExitCode.INVALID_STATE
            )
        return state

    def save(self, state: State) -> State:
        state = state.stamped(self._clock())
        data = state_to_dict(state)
        problems = schema_errors(json.loads(json.dumps(data)), STATE_SCHEMA_FILE) or state_problems(
            state, self.workflow
        )
        if problems:
            raise AgentflowError(f"refusing to save invalid state:{_INDENT}{_INDENT.join(problems)}", ExitCode.INVALID_STATE)
        written = json.dumps(data, indent=JSON_INDENT, ensure_ascii=False) + "\n"
        write_text_atomic(self.state_path, written)
        Integrity(self.state_path.parent).record_state(sha256_hex(written.encode(ENCODING)))
        self.write_state_md(state)
        return state

    def write_state_md(self, state: State) -> None:
        write_text_atomic(self.state_md_path, render_state_md(state, self.workflow))


def state_problems(state: State, workflow: Workflow) -> list[str]:
    """Rules JSON Schema cannot express: unique ids, a real in-flight active task, known steps,
    and step statuses that fit the task status.

    Only in-flight tasks must sit on a step the workflow defines; finished tasks may
    refer to steps a later workflow version dropped.
    """
    problems = [f"duplicate task id '{task_id}'" for task_id, n in Counter(t.id for t in state.tasks).items() if n > 1]
    active = state.active_task()
    if state.active_task_id is not None and active is None:
        problems.append(f"active_task_id '{state.active_task_id}' matches no task")
    elif active is not None and active.status not in IN_FLIGHT_TASK_STATUSES:
        problems.append(f"active task {active.id} is {active.status}")
    problems += [
        f"task {task.id}: step '{task.current_step}' is not in workflow '{workflow.family}'"
        for task in unknown_step_tasks(state, workflow)
    ]
    problems += [
        f"task {task.id}: step status '{task.step_status}' does not fit task status '{task.status}'"
        for task in state.tasks
        if task.step_status not in ALLOWED_STEP_STATUSES[task.status]
    ]
    return problems


def unknown_step_tasks(state: State, workflow: Workflow) -> list[Task]:
    """In-flight tasks whose current step the workflow does not define."""
    return [
        task
        for task in state.tasks
        if task.status in IN_FLIGHT_TASK_STATUSES and workflow.get_step(task.current_step) is None
    ]


def render_state_md(state: State, workflow: Workflow) -> str:
    task = state.active_task()
    lines = [
        GENERATED_NOTE,
        "",
        "# agentflow state",
        "",
        f"- Workflow: {workflow.family}",
        f"- Updated: {state.updated_at or NONE_TEXT}",
        f"- Active task: {_task_label(task)}",
    ]
    if task is not None:
        step = workflow.get_step(task.current_step)
        step_text = describe_step(step) if step else f"step '{task.current_step}'"
        lines += [
            f"- Current step: {step_text}, {task.step_status}",
            f"- Rework rounds: {task.loop_round}/{workflow.max_rounds}",
            f"- Branch: {task.branch or NONE_TEXT}",
        ]
        if task.size:
            lines.append(f"- Size: {task.size}")
        if task.type:
            lines.append(f"- Type: {task.type}")
        if task.roadmap:
            lines.append(f"- Roadmap: {task.roadmap}")
    lines += [f"- Next: {describe_action(next_action(workflow, task))}", "", "## Tasks", ""]
    if not state.tasks:
        lines.append("No tasks yet.")
    else:
        lines += ["| ID | Title | Status | Step | Step status | Branch |", "|---|---|---|---|---|---|"]
        lines += [
            f"| {t.id} | {_cell(t.title)} | {t.status} | {t.current_step} | {t.step_status} | {_cell(t.branch or NONE_TEXT)} |"
            for t in state.tasks
        ]
    return "\n".join(lines) + "\n"


def _task_label(task: Task | None) -> str:
    return NONE_TEXT if task is None else f"{task.id} {task.title}"


def _cell(text: str) -> str:
    return text.replace("|", "\\|")
