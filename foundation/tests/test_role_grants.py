KNOWN = {"lead", "builder", "checker"}
READ_ONLY = {"lead", "checker"}


def policy():
    return WorkflowGrantPolicy(KNOWN, READ_ONLY)


def refused(role, tool):
    with pytest.raises(AgentflowError) as raised:
        policy().check(role, tool)
    assert raised.value.code == ExitCode.ROLE_GRANT_REFUSED
    return str(raised.value)


