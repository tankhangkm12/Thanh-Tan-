def agent_file(directory, name, tools):
    directory.mkdir(parents=True, exist_ok=True)
    text = f"---\nname: {name}\ndescription: {name} things.\ntools: {tools}\nmodel: inherit\n---\n\nYou are {name}.\n"
    (directory / f"{name}.md").write_text(text, encoding="utf-8")


@pytest.fixture
def ws(gitflow_repo, tmp_path, monkeypatch, capsys):
    data = copy.deepcopy(SAMPLE_WORKFLOW)
    data["tiered_roles"] = ["builder"]
    data["read_only_roles"] = ["lead", "checker"]
    data["agent_dirs"] = {"claude": "claude/agents"}
    data["steps"][1]["gates"] = ["plan-valid"]  # "build" plays the plan step
    path = write_workflow(tmp_path / "plugin" / "workflow.yaml", data)
    agents = tmp_path / "plugin" / "claude" / "agents"
    for name in ("builder-fast", "builder-deep", "lead", "checker"):
        agent_file(agents, name, "Read, Bash")
    monkeypatch.chdir(gitflow_repo)
    assert main(["init", "--workflow", str(path)]) == ExitCode.OK
    capsys.readouterr()
    return gitflow_repo


def project_agents(repo):
    return sorted(path.name for path in (repo / ".claude" / "agents").glob("*.md")) if (repo / ".claude" / "agents").is_dir() else []


def test_grant_makes_a_project_agent_per_tier_and_keeps_it_out_of_git(ws, capsys):
    assert main(["role", "grant", "builder", "mcp__fake__*"]) == ExitCode.OK
    out = capsys.readouterr().out
    assert "builder may use mcp__fake__*" in out
    assert project_agents(ws) == ["project-builder-deep.md", "project-builder-fast.md"]
    assert "mcp__fake__*" in (ws / ".claude" / "agents" / "project-builder-fast.md").read_text(encoding="utf-8")
    assert subprocess.run(["git", "status", "--porcelain"], cwd=ws, capture_output=True, text=True).stdout == ""  # excluded
    assert ".claude/agents/project-*.md" in (ws / ".git" / "info" / "exclude").read_text(encoding="utf-8")
    config = yaml.safe_load((ws / ".ThanhTan" / "config.yaml").read_text(encoding="utf-8"))
    assert config["role_grants"] == {"builder": ["mcp__fake__*"]}


def test_a_second_grant_adds_to_the_first_and_a_repeat_is_refused(ws, capsys):
    main(["role", "grant", "builder", "mcp__fake__*"])
    assert main(["role", "grant", "builder", "mcp__other__get"]) == ExitCode.OK
    text = (ws / ".claude" / "agents" / "project-builder-deep.md").read_text(encoding="utf-8")
    assert "mcp__fake__*, mcp__other__get" in text
    assert main(["role", "grant", "builder", "mcp__other__get"]) == ExitCode.ROLE_GRANT_REFUSED


def test_a_reviewer_like_role_is_refused_a_write_tool_but_gets_a_read_tool(ws, capsys):
    assert main(["role", "grant", "checker", "mcp__fake__write_note"]) == ExitCode.ROLE_GRANT_REFUSED
    assert "only reads" in capsys.readouterr().err
    assert project_agents(ws) == []
    assert main(["role", "grant", "checker", "mcp__fake__get_note"]) == ExitCode.OK
    assert project_agents(ws) == ["project-checker.md"]
    assert main(["role", "grant", "checker", "mcp__fake__*"]) == ExitCode.ROLE_GRANT_REFUSED


def test_a_grant_for_a_role_whose_plugin_agent_is_missing_changes_nothing(ws, capsys):
    (ws.parent / "plugin" / "claude" / "agents" / "builder-deep.md").unlink()
    assert main(["role", "grant", "builder", "mcp__fake__*"]) == ExitCode.ROLE_GRANT_REFUSED
    assert "builder-deep" in capsys.readouterr().err
    assert project_agents(ws) == []
    main(["role", "list"])
    assert "no role has extra tools" in capsys.readouterr().out


def test_revoke_removes_the_tool_and_finally_the_agents(ws, capsys):
    main(["role", "grant", "builder", "mcp__a"])
    main(["role", "grant", "builder", "mcp__b"])
    assert main(["role", "revoke", "builder", "mcp__a"]) == ExitCode.OK
    text = (ws / ".claude" / "agents" / "project-builder-fast.md").read_text(encoding="utf-8")
    assert "mcp__b" in text and "mcp__a" not in text
    assert main(["role", "revoke", "builder", "mcp__b"]) == ExitCode.OK
    assert project_agents(ws) == []
    assert main(["role", "revoke", "builder", "mcp__b"]) == ExitCode.ROLE_GRANT_REFUSED


def test_list_shows_grants_agents_state_and_the_antigravity_note(ws, capsys):
    main(["role", "grant", "builder", "mcp__fake__*"])
    capsys.readouterr()
    assert main(["role", "list"]) == ExitCode.OK
    out = capsys.readouterr().out
    assert "builder: mcp__fake__*" in out
    assert "project-builder-fast (current)" in out and "project-builder-deep (current)" in out
    assert "Antigravity: its agents see every MCP server" in out
    agent_file(ws.parent / "plugin" / "claude" / "agents", "builder-fast", "Read, Bash, Grep")  # the plugin changed
    main(["role", "list"])
    out = capsys.readouterr().out
    assert "project-builder-fast (stale)" in out and "agentflow role sync" in out
    assert main(["role", "sync"]) == ExitCode.OK
    assert "Grep" in (ws / ".claude" / "agents" / "project-builder-fast.md").read_text(encoding="utf-8")
    assert main(["role", "sync"]) == ExitCode.OK
    assert "up to date" in capsys.readouterr().out.splitlines()[-1]


