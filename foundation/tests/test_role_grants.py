@pytest.mark.parametrize("command", ["agentflow role grant builder mcp__x", "agentflow role revoke builder mcp__x", "agentflow role sync"])
def test_an_agent_cannot_run_the_role_commands_that_change_grants(ws, command):
    class Branches:
        def current_branch(self, directory):
            return "feature/x"

        def branch_exists(self, directory, name):
            return True

    class Workspaces:
        def has_workspace(self, directory):
            return True

    verdict = evaluate(command, ws, Branches(), Workspaces())
    assert verdict.rule is GuardRule.PERSON_ONLY
    assert evaluate("agentflow role list", ws, Branches(), Workspaces()).decision == "allow"


def test_the_generated_project_agents_are_protected_from_the_agents_own_write_tools(ws):
    main(["role", "grant", "builder", "mcp__fake__*"])
    policy = WorkspaceWritePolicy()
    assert policy.is_protected(".claude/agents/project-builder-fast.md", ws)
    assert policy.is_protected(ws / ".claude" / "agents" / "project-new.md", ws)
    assert not policy.is_protected(".claude/agents/mine.md", ws)
    assert not policy.is_protected(".claude/project-x.md", ws)
    assert not policy.is_protected("src/.claude/agents/project-x.md", ws)  # no workspace there


