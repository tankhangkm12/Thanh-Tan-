PLUGIN_AGENT = """---
name: builder-fast
description: Builds things.
tools: Read, Edit, mcp__plugin_x_y__status
model: sonnet
effort: low
---
<!-- Generated by tools/build.py from src/roles/builder.md. Do not edit: edit the source and rebuild. -->

You are the builder.
"""


def test_the_overlay_implements_the_protocol(tmp_path):
    assert isinstance(ClaudeAgentOverlay(tmp_path, []), AgentOverlay)


def make_overlay(tmp_path):
    source = tmp_path / "plugin" / "claude" / "agents"
    source.mkdir(parents=True)
    (source / "builder-fast.md").write_text(PLUGIN_AGENT, encoding="utf-8")
    project = tmp_path / "project"
    project.mkdir()
    return ClaudeAgentOverlay(project, [source]), project


def test_the_overlay_copies_the_plugin_agent_and_adds_the_tools(tmp_path):
    overlay, _ = make_overlay(tmp_path)
    files = overlay.render({"builder-fast": ("mcp__fake__*", "Read")})
    assert list(files) == ["project-builder-fast.md"]
    text = files["project-builder-fast.md"]
    header = yaml.safe_load(text.split("---")[1])
    assert header["name"] == "project-builder-fast"
    assert header["tools"] == "Read, Edit, mcp__plugin_x_y__status, mcp__fake__*"  # added once, in order
    assert (header["model"], header["effort"]) == ("sonnet", "low")
    assert "Builds things." in header["description"] and "mcp__fake__*" in header["description"]
    assert "Generated by agentflow role sync from builder-fast.md (sha256 " in text
    assert "tools/build.py" not in text and text.rstrip().endswith("You are the builder.")


def test_the_overlay_writes_reports_state_and_removes_what_is_no_longer_wanted(tmp_path):
    overlay, project = make_overlay(tmp_path)
    files = overlay.render({"builder-fast": ("mcp__fake__*",)})
    assert overlay.state(files) == {"project-builder-fast.md": "missing"}
    assert overlay.write(files) == ["wrote .claude/agents/project-builder-fast.md"]
    assert overlay.state(files) == {"project-builder-fast.md": "current"}
    assert overlay.write(files) == []
    changed = overlay.render({"builder-fast": ("mcp__fake__*", "mcp__other")})
    assert overlay.state(changed) == {"project-builder-fast.md": "stale"}
    mine = project / ".claude" / "agents" / "mine.md"
    mine.write_text("a person's own agent", encoding="utf-8")
    assert overlay.write({}) == ["removed .claude/agents/project-builder-fast.md"]
    assert mine.is_file()  # only what agentflow generated goes
    (project / ".claude" / "agents" / "project-handmade.md").write_text("handmade", encoding="utf-8")
    assert overlay.write({}) == []  # a project-* file agentflow did not generate stays


def test_a_missing_plugin_agent_is_an_error(tmp_path):
    overlay, _ = make_overlay(tmp_path)
    with pytest.raises(AgentflowError, match="was not found") as raised:
        overlay.render({"ghost": ("mcp__fake",)})
    assert raised.value.code == ExitCode.ROLE_GRANT_REFUSED


